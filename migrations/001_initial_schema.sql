CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_prepare_supply_chain_event()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    parent_event_time TIMESTAMPTZ;
    parent_causal_depth INTEGER;
BEGIN
    IF NEW.order_id IS NOT NULL AND NEW.order_line_id IS NOT NULL THEN
        IF NOT EXISTS (
            SELECT 1
            FROM order_lines ol
            WHERE ol.order_line_id = NEW.order_line_id
              AND ol.order_id = NEW.order_id
        ) THEN
            RAISE EXCEPTION
                'order_line_id % does not belong to order_id %',
                NEW.order_line_id, NEW.order_id;
        END IF;
    END IF;

    IF NEW.purchase_order_id IS NOT NULL AND NEW.po_line_id IS NOT NULL THEN
        IF NOT EXISTS (
            SELECT 1
            FROM po_lines pl
            WHERE pl.po_line_id = NEW.po_line_id
              AND pl.purchase_order_id = NEW.purchase_order_id
        ) THEN
            RAISE EXCEPTION
                'po_line_id % does not belong to purchase_order_id %',
                NEW.po_line_id, NEW.purchase_order_id;
        END IF;
    END IF;

    IF NEW.caused_by_event_id IS NULL THEN
        NEW.causal_depth := 0;
    ELSE
        SELECT event_time, causal_depth
          INTO parent_event_time, parent_causal_depth
          FROM supply_chain_events
         WHERE event_id = NEW.caused_by_event_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'caused_by_event_id % does not exist',
                NEW.caused_by_event_id;
        END IF;

        IF parent_event_time > NEW.event_time THEN
            RAISE EXCEPTION
                'causal event time must not move backwards: parent %, child %',
                parent_event_time, NEW.event_time;
        END IF;

        IF parent_causal_depth >= 64 THEN
            RAISE EXCEPTION 'causal depth exceeds the supported limit of 64';
        END IF;

        NEW.causal_depth := parent_causal_depth + 1;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_reject_event_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'supply_chain_events is append-only; add a corrective event instead';
END;
$$;

CREATE OR REPLACE FUNCTION fn_validate_causal_link()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    cause_time TIMESTAMPTZ;
    effect_time TIMESTAMPTZ;
BEGIN
    SELECT event_time INTO cause_time
      FROM supply_chain_events
     WHERE event_id = NEW.cause_event_id;

    SELECT event_time INTO effect_time
      FROM supply_chain_events
     WHERE event_id = NEW.effect_event_id;

    IF cause_time > effect_time THEN
        RAISE EXCEPTION
            'causal link time order is invalid: cause %, effect %',
            cause_time, effect_time;
    END IF;

    IF EXISTS (
        WITH RECURSIVE ancestors(event_id, depth) AS (
            SELECT NEW.cause_event_id, 0
            UNION
            SELECT p.parent_id, a.depth + 1
              FROM ancestors a
              CROSS JOIN LATERAL (
                    SELECT e.caused_by_event_id AS parent_id
                      FROM supply_chain_events e
                     WHERE e.event_id = a.event_id
                       AND e.caused_by_event_id IS NOT NULL
                    UNION
                    SELECT cl.cause_event_id AS parent_id
                      FROM causal_links cl
                     WHERE cl.effect_event_id = a.event_id
              ) p
             WHERE p.parent_id IS NOT NULL
               AND a.depth < 64
        )
        SELECT 1
          FROM ancestors
         WHERE event_id = NEW.effect_event_id
    ) THEN
        RAISE EXCEPTION
            'causal link % -> % would create a cycle',
            NEW.cause_event_id, NEW.effect_event_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_audit_row()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    old_row JSONB;
    new_row JSONB;
    row_key TEXT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        old_row := to_jsonb(OLD);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        new_row := to_jsonb(NEW);
    END IF;

    row_key := COALESCE(
        new_row ->> 'entity_id',
        new_row ->> 'location_id',
        new_row ->> 'item_id',
        new_row ->> 'order_id',
        new_row ->> 'order_line_id',
        new_row ->> 'purchase_order_id',
        new_row ->> 'po_line_id',
        new_row ->> 'production_order_id',
        new_row ->> 'shipment_id',
        new_row ->> 'commitment_id',
        old_row ->> 'entity_id',
        old_row ->> 'location_id',
        old_row ->> 'item_id',
        old_row ->> 'order_id',
        old_row ->> 'order_line_id',
        old_row ->> 'purchase_order_id',
        old_row ->> 'po_line_id',
        old_row ->> 'production_order_id',
        old_row ->> 'shipment_id',
        old_row ->> 'commitment_id'
    );

    INSERT INTO audit_log (
        table_name, operation, record_key, old_data, new_data, changed_by
    )
    VALUES (
        TG_TABLE_NAME,
        LEFT(TG_OP, 1),
        row_key,
        old_row,
        new_row,
        COALESCE(current_setting('supplytrace.actor', TRUE), current_user)
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

