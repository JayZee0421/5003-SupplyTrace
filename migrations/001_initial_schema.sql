-- SupplyTrace database schema v1
-- Target: PostgreSQL 16+
-- This file is intended to be loaded into a clean database before sample_data.sql.

BEGIN;

CREATE TYPE entity_role AS ENUM (
    'SUPPLIER',
    'FACTORY',
    'WAREHOUSE',
    'CARRIER',
    'CUSTOMER'
);

CREATE TYPE event_category AS ENUM (
    'ORDER',
    'PROCUREMENT',
    'QUALITY',
    'PRODUCTION',
    'LOGISTICS',
    'DELIVERY'
);

CREATE TYPE event_status AS ENUM (
    'NORMAL',
    'WARNING',
    'FAILED',
    'COMPLETED',
    'CANCELLED'
);

CREATE TYPE order_status AS ENUM (
    'DRAFT',
    'CONFIRMED',
    'IN_PRODUCTION',
    'SHIPPED',
    'DELIVERED',
    'DELAYED',
    'CANCELLED'
);

CREATE TYPE purchase_order_status AS ENUM (
    'DRAFT',
    'ISSUED',
    'CONFIRMED',
    'COMPLETED',
    'DELAYED',
    'CANCELLED'
);

CREATE TYPE production_status AS ENUM (
    'PLANNED',
    'IN_PROGRESS',
    'COMPLETED',
    'ON_HOLD',
    'CANCELLED'
);

CREATE TYPE shipment_status AS ENUM (
    'PLANNED',
    'IN_TRANSIT',
    'ARRIVED',
    'DELIVERED',
    'DELAYED',
    'CANCELLED'
);

CREATE TYPE commitment_status AS ENUM (
    'ACTIVE',
    'SUPERSEDED',
    'MET',
    'MISSED',
    'CANCELLED'
);

CREATE TYPE causal_link_type AS ENUM (
    'CONTRIBUTING',
    'ALTERNATIVE',
    'CORRECTIVE'
);

CREATE TABLE entities (
    entity_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_code     TEXT NOT NULL UNIQUE,
    entity_name     TEXT NOT NULL,
    entity_type     entity_role NOT NULL,
    country_code    CHAR(2),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    attributes      JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_entities_attributes_object
        CHECK (jsonb_typeof(attributes) = 'object')
);

COMMENT ON TABLE entities IS
    'Shared master record for suppliers, factories, warehouses, carriers and customers.';
COMMENT ON COLUMN entities.attributes IS
    'Optional type-specific attributes that are not used by causal traversal.';

CREATE TABLE locations (
    location_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code   TEXT NOT NULL UNIQUE,
    location_name   TEXT NOT NULL,
    owner_entity_id BIGINT REFERENCES entities(entity_id) ON DELETE RESTRICT,
    city            TEXT,
    region          TEXT,
    country_code    CHAR(2),
    longitude       NUMERIC(9,6),
    latitude        NUMERIC(9,6),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_locations_longitude
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_locations_latitude
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90)
);

CREATE TABLE items (
    item_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_code       TEXT NOT NULL UNIQUE,
    item_name       TEXT NOT NULL,
    item_category   TEXT NOT NULL,
    unit_of_measure TEXT NOT NULL,
    is_lot_tracked  BOOLEAN NOT NULL DEFAULT FALSE,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE orders (
    order_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    TEXT NOT NULL UNIQUE,
    customer_id     BIGINT NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
    ordered_at      TIMESTAMPTZ NOT NULL,
    required_date   DATE NOT NULL,
    currency_code   CHAR(3) NOT NULL DEFAULT 'CNY',
    status          order_status NOT NULL DEFAULT 'DRAFT',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_orders_required_date
        CHECK (required_date >= ordered_at::DATE)
);

CREATE TABLE order_lines (
    order_line_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    line_number     INTEGER NOT NULL,
    item_id         BIGINT NOT NULL REFERENCES items(item_id) ON DELETE RESTRICT,
    quantity        NUMERIC(18,3) NOT NULL,
    unit_price      NUMERIC(18,4) NOT NULL,
    required_date   DATE NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_order_lines_number UNIQUE (order_id, line_number),
    CONSTRAINT ck_order_lines_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_lines_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE purchase_orders (
    purchase_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number          TEXT NOT NULL UNIQUE,
    supplier_id        BIGINT NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
    issued_at          TIMESTAMPTZ NOT NULL,
    promised_date      DATE,
    status             purchase_order_status NOT NULL DEFAULT 'DRAFT',
    created_at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_purchase_orders_promised_date
        CHECK (promised_date IS NULL OR promised_date >= issued_at::DATE)
);

CREATE TABLE po_lines (
    po_line_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id  BIGINT NOT NULL
        REFERENCES purchase_orders(purchase_order_id) ON DELETE RESTRICT,
    line_number        INTEGER NOT NULL,
    item_id            BIGINT NOT NULL REFERENCES items(item_id) ON DELETE RESTRICT,
    quantity           NUMERIC(18,3) NOT NULL,
    quantity_received  NUMERIC(18,3) NOT NULL DEFAULT 0,
    unit_price         NUMERIC(18,4) NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_po_lines_number UNIQUE (purchase_order_id, line_number),
    CONSTRAINT ck_po_lines_quantity CHECK (quantity > 0),
    CONSTRAINT ck_po_lines_received
        CHECK (quantity_received >= 0 AND quantity_received <= quantity),
    CONSTRAINT ck_po_lines_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE purchase_line_allocations (
    po_line_id          BIGINT NOT NULL
        REFERENCES po_lines(po_line_id) ON DELETE RESTRICT,
    order_line_id       BIGINT NOT NULL
        REFERENCES order_lines(order_line_id) ON DELETE RESTRICT,
    allocated_quantity  NUMERIC(18,3) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (po_line_id, order_line_id),
    CONSTRAINT ck_purchase_line_allocations_quantity
        CHECK (allocated_quantity > 0)
);

CREATE TABLE production_orders (
    production_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_number   TEXT NOT NULL UNIQUE,
    factory_id           BIGINT NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
    source_order_line_id BIGINT REFERENCES order_lines(order_line_id) ON DELETE RESTRICT,
    output_item_id       BIGINT NOT NULL REFERENCES items(item_id) ON DELETE RESTRICT,
    quantity             NUMERIC(18,3) NOT NULL,
    planned_start        TIMESTAMPTZ NOT NULL,
    planned_end          TIMESTAMPTZ NOT NULL,
    actual_start         TIMESTAMPTZ,
    actual_end           TIMESTAMPTZ,
    status               production_status NOT NULL DEFAULT 'PLANNED',
    created_at           TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_production_orders_quantity CHECK (quantity > 0),
    CONSTRAINT ck_production_orders_planned_time
        CHECK (planned_end >= planned_start),
    CONSTRAINT ck_production_orders_actual_time
        CHECK (actual_start IS NULL OR actual_end IS NULL OR actual_end >= actual_start)
);

CREATE TABLE shipments (
    shipment_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_number       TEXT NOT NULL UNIQUE,
    carrier_id            BIGINT NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
    origin_location_id    BIGINT NOT NULL REFERENCES locations(location_id) ON DELETE RESTRICT,
    destination_location_id BIGINT NOT NULL
        REFERENCES locations(location_id) ON DELETE RESTRICT,
    planned_departure     TIMESTAMPTZ NOT NULL,
    planned_arrival       TIMESTAMPTZ NOT NULL,
    actual_departure      TIMESTAMPTZ,
    actual_arrival        TIMESTAMPTZ,
    status                shipment_status NOT NULL DEFAULT 'PLANNED',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_shipments_planned_time
        CHECK (planned_arrival >= planned_departure),
    CONSTRAINT ck_shipments_actual_time
        CHECK (actual_departure IS NULL OR actual_arrival IS NULL
               OR actual_arrival >= actual_departure)
);

CREATE TABLE shipment_lines (
    shipment_line_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id      BIGINT NOT NULL REFERENCES shipments(shipment_id) ON DELETE RESTRICT,
    order_line_id    BIGINT REFERENCES order_lines(order_line_id) ON DELETE RESTRICT,
    po_line_id       BIGINT REFERENCES po_lines(po_line_id) ON DELETE RESTRICT,
    quantity         NUMERIC(18,3) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_shipment_lines_one_reference
        CHECK (num_nonnulls(order_line_id, po_line_id) = 1),
    CONSTRAINT ck_shipment_lines_quantity CHECK (quantity > 0)
);

CREATE TABLE delivery_commitments (
    commitment_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_line_id           BIGINT NOT NULL
        REFERENCES order_lines(order_line_id) ON DELETE RESTRICT,
    version                 INTEGER NOT NULL,
    committed_date          DATE NOT NULL,
    changed_at              TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    reason                  TEXT,
    status                  commitment_status NOT NULL DEFAULT 'ACTIVE',
    supersedes_commitment_id BIGINT
        REFERENCES delivery_commitments(commitment_id) ON DELETE RESTRICT,
    CONSTRAINT uq_delivery_commitments_version
        UNIQUE (order_line_id, version),
    CONSTRAINT ck_delivery_commitments_version CHECK (version > 0),
    CONSTRAINT ck_delivery_commitments_not_self
        CHECK (supersedes_commitment_id IS NULL
               OR supersedes_commitment_id <> commitment_id)
);

CREATE UNIQUE INDEX uq_delivery_commitments_active_line
    ON delivery_commitments(order_line_id)
    WHERE status = 'ACTIVE';

CREATE TABLE event_types (
    event_type_code      TEXT PRIMARY KEY,
    event_name           TEXT NOT NULL,
    category             event_category NOT NULL,
    default_status       event_status NOT NULL DEFAULT 'NORMAL',
    is_exception         BOOLEAN NOT NULL DEFAULT FALSE,
    gs1_epcis_mapping    TEXT,
    mapping_note         TEXT,
    description          TEXT NOT NULL,
    is_active            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE supply_chain_events (
    event_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type_code      TEXT NOT NULL
        REFERENCES event_types(event_type_code) ON DELETE RESTRICT,
    event_time           TIMESTAMPTZ NOT NULL,
    recorded_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    entity_type          entity_role NOT NULL,
    entity_id            BIGINT NOT NULL REFERENCES entities(entity_id) ON DELETE RESTRICT,
    location_id          BIGINT REFERENCES locations(location_id) ON DELETE RESTRICT,
    order_id             BIGINT REFERENCES orders(order_id) ON DELETE RESTRICT,
    order_line_id        BIGINT REFERENCES order_lines(order_line_id) ON DELETE RESTRICT,
    purchase_order_id    BIGINT REFERENCES purchase_orders(purchase_order_id) ON DELETE RESTRICT,
    po_line_id           BIGINT REFERENCES po_lines(po_line_id) ON DELETE RESTRICT,
    production_order_id  BIGINT
        REFERENCES production_orders(production_order_id) ON DELETE RESTRICT,
    shipment_id          BIGINT REFERENCES shipments(shipment_id) ON DELETE RESTRICT,
    delivery_commitment_id BIGINT
        REFERENCES delivery_commitments(commitment_id) ON DELETE RESTRICT,
    quantity             NUMERIC(18,3),
    status               event_status NOT NULL DEFAULT 'NORMAL',
    message              TEXT,
    caused_by_event_id   BIGINT REFERENCES supply_chain_events(event_id) ON DELETE RESTRICT,
    causal_depth         INTEGER NOT NULL DEFAULT 0,
    payload              JSONB NOT NULL DEFAULT '{}'::JSONB,
    recorded_by          TEXT NOT NULL DEFAULT current_user,
    CONSTRAINT ck_events_quantity CHECK (quantity IS NULL OR quantity > 0),
    CONSTRAINT ck_events_causal_depth CHECK (causal_depth BETWEEN 0 AND 64),
    CONSTRAINT ck_events_payload_object
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_events_payload_size
        CHECK (pg_column_size(payload) <= 32768)
);

CREATE TABLE causal_links (
    cause_event_id   BIGINT NOT NULL
        REFERENCES supply_chain_events(event_id) ON DELETE RESTRICT,
    effect_event_id  BIGINT NOT NULL
        REFERENCES supply_chain_events(event_id) ON DELETE RESTRICT,
    link_type        causal_link_type NOT NULL DEFAULT 'CONTRIBUTING',
    weight           NUMERIC(4,3) NOT NULL DEFAULT 1.000,
    note             TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (cause_event_id, effect_event_id),
    CONSTRAINT ck_causal_links_not_self CHECK (cause_event_id <> effect_event_id),
    CONSTRAINT ck_causal_links_weight CHECK (weight > 0 AND weight <= 1)
);

COMMENT ON TABLE causal_links IS
    'Additional many-to-many causal edges. The primary parent remains in supply_chain_events.caused_by_event_id.';

CREATE TABLE audit_log (
    audit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name     TEXT NOT NULL,
    operation      CHAR(1) NOT NULL,
    record_key     TEXT,
    old_data       JSONB,
    new_data       JSONB,
    changed_by     TEXT NOT NULL DEFAULT current_user,
    changed_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_audit_log_operation CHECK (operation IN ('I', 'U', 'D')),
    CONSTRAINT ck_audit_log_has_value
        CHECK (old_data IS NOT NULL OR new_data IS NOT NULL)
);

